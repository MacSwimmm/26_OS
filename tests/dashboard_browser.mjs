// Run with: node tests/dashboard_browser.mjs (Playwright runtime required).
import assert from 'node:assert/strict';
import fs from 'node:fs';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
fs.mkdirSync('results/browser', {recursive:true});
const base = process.env.DASHBOARD_URL || 'http://127.0.0.1:8765';
const browser = await chromium.launch({...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{}),headless:true});
const checks=[], errors=[];
const record=(name,detail={})=>{checks.push({name,passed:true,...detail});console.log(`PASS ${name}`)};
try {
  const page=await browser.newPage({viewport:{width:1600,height:1000},locale:'zh-CN',reducedMotion:'reduce'});
  page.on('pageerror',error=>errors.push(error.message));
  let runRequests=0;
  page.on('request',request=>{if(request.url().endsWith('/api/run'))runRequests++});
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#playState').textContent==='等待开始' && !document.querySelector('#heroRun').disabled);
  assert.equal(await page.locator('#timeLabel').textContent(),'t = 0');
  assert.equal(await page.locator('#toast').getAttribute('class'),'toast');
  record('initial load is ready at t=0 without a completion message');
  await page.screenshot({path:'results/browser/teaflow-refined-hero.png'});

  await page.route('**/api/run',async route=>{await new Promise(resolve=>setTimeout(resolve,250));await route.continue()});
  const before=runRequests;
  await page.evaluate(()=>{document.querySelector('#heroRun').click();document.querySelector('#runButton').click();document.querySelector('#heroRun').click()});
  await page.waitForFunction(()=>document.querySelector('#playState').textContent==='运行中');
  await page.waitForFunction(()=>Number(document.querySelector('#timeRange').value)>0);
  assert.equal(runRequests-before,1);
  assert.equal(await page.locator('#toast.show').count(),0);
  record('hero start auto plays; overlapping starts submit one request; no success toast');
  await page.locator('#playButton').click();
  const paused=await page.locator('#timeRange').inputValue();
  await page.waitForTimeout(1050);
  assert.equal(await page.locator('#timeRange').inputValue(),paused);
  assert.equal(await page.locator('#playState').textContent(),'已暂停');
  record('pause holds the clock');

  await page.locator('#speed').selectOption('180');
  await page.locator('#playButton').click();
  await page.waitForFunction(()=>document.querySelector('#playState').textContent==='仿真已结束');
  assert.equal(await page.locator('#timeRange').inputValue(),await page.locator('#timeRange').getAttribute('max'));
  assert.match(await page.locator('#playButton').textContent(),/重播/);
  record('resume at 5x reaches the final tick and stops');
  await page.locator('#stepBack').click();
  assert.equal(await page.locator('#playState').textContent(),'已暂停');
  await page.locator('#timeRange').fill('3');
  await page.locator('#timeRange').dispatchEvent('input');
  assert.equal(await page.locator('#timeLabel').textContent(),'t = 3');
  assert.equal(await page.locator('#playState').textContent(),'已暂停');
  record('step and scrub pause at the chosen tick');

  await page.locator('#runButton').click();
  await page.waitForFunction(()=>document.querySelector('#playState').textContent==='运行中'&&Number(document.querySelector('#timeRange').value)===0);
  await page.locator('#playButton').click();
  record('header rerun resets the clock and starts playback');
  await page.screenshot({path:'results/browser/teaflow-refined-session.png'});

  await page.locator('#monitorNext').click();
  assert.equal(await page.locator('.monitor-slide.is-active').getAttribute('data-widget'),'tasks');
  await page.locator('#tab-resources').click();
  await page.locator('#tab-resources').press('ArrowRight');
  assert.equal(await page.locator('.monitor-slide.is-active').getAttribute('data-widget'),'chart');
  await page.locator('#tab-chart').press('End');
  assert.equal(await page.locator('.monitor-slide.is-active').getAttribute('data-widget'),'features');
  assert.equal(await page.locator('#monitorNext').isDisabled(),true);
  await page.locator('#tab-features').press('Home');
  assert.equal(await page.locator('#monitorPrev').isDisabled(),true);
  record('carousel arrows, tabs, keyboard and edge buttons agree');
  await page.locator('#tab-resources').click();
  await page.screenshot({path:'results/browser/teaflow-refined-resources.png'});

  await page.locator('#scenarioTrigger').click();
  await page.locator('[data-scenario="non_preemptive"]').click();
  await page.waitForFunction(()=>document.querySelector('#sessionScenario').textContent==='非抢占调度'&&document.querySelector('#playState').textContent==='运行中');
  await page.locator('#playButton').click();
  record('scenario menu selects and starts the requested single scenario');
  const preserved=await page.locator('#timeRange').inputValue();
  await page.locator('#scenario').selectOption('compare');
  await page.locator('#runButton').click();
  await page.waitForFunction(()=>document.querySelector('#view-experiments').classList.contains('active')&&document.querySelectorAll('.compare-tile').length===5);
  record('strategy comparison renders five real results');
  await page.locator('#experimentMode').selectOption('deadlock');
  await page.waitForFunction(()=>document.querySelector('.compare-tile h3')?.textContent==='银行家避免'&&!document.querySelector('#runButton').disabled);
  assert.match(await page.locator('#experimentContent').textContent(),/检测并回滚恢复/);
  record('deadlock experiment renders avoidance, detection and recovery');
  await page.locator('[data-view="overview"]').click();
  assert.equal(await page.locator('#timeRange').inputValue(),preserved);
  await page.locator('#playButton').click();
  await page.waitForFunction(()=>document.querySelector('#playState').textContent==='运行中');
  await page.locator('#playButton').click();
  record('returning from experiments preserves playable simulation snapshots');

  await page.locator('#tab-resources').click();
  await page.locator('#openSettings').click();
  await page.locator('#customTitle').fill('操作系统课程演示');
  await page.locator('#customProject').fill('自定义项目');
  await page.locator('#accentText').fill('#69e7b4');
  await page.locator('#customCards').fill('[{"label":"课程组","value":"OS-04","note":"自定义内容"}]');
  await page.locator('[data-widget-switch="resources"]').click();
  await page.locator('#saveConfig').click();
  assert.equal(await page.locator('#pageTitle').textContent(),'操作系统课程演示');
  assert.equal(await page.locator('#sessionTitle').textContent(),'自定义项目');
  assert.equal(await page.locator('#tab-resources').count(),0);
  assert.notEqual(await page.locator('.monitor-slide.is-active').getAttribute('data-widget'),'resources');
  assert.match(await page.locator('#metrics').textContent(),/OS-04/);
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#runButton').disabled);
  assert.equal(await page.locator('#pageTitle').textContent(),'操作系统课程演示');
  assert.equal(await page.locator('#tab-resources').count(),0);
  record('custom text, accent, metrics and hidden active module persist with safe fallback');
  await page.locator('#openSettings').click();
  assert.equal(await page.locator('#drawer').evaluate(el=>el.inert),false);
  await page.locator('#closeSettings').press('Escape');
  assert.equal(await page.locator('#drawer').evaluate(el=>el.inert),true);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'openSettings');
  record('settings Escape closes the dialog and restores keyboard focus');
  await page.locator('#openSettings').click();
  while(await page.locator('[data-widget-switch][aria-checked="true"]').count())await page.locator('[data-widget-switch][aria-checked="true"]').first().click();
  await page.locator('#saveConfig').click();
  assert.equal(await page.locator('.monitor-empty').isVisible(),true);
  assert.equal(await page.locator('#monitorNext').isDisabled(),true);
  await page.locator('#openSettings').click();
  await page.locator('#resetConfig').click();await page.locator('#closeSettings').click();
  assert.equal(await page.locator('.monitor-tab').count(),6);
  record('all modules hidden yields an empty state; reset restores the full carousel');

  await page.locator('#scenario').selectOption('baseline');
  await page.unroute('**/api/run');
  await page.route('**/api/run',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'测试引擎暂时不可用'})}));
  await page.locator('[data-view="tasks"]').click();
  await page.locator('#runButton').click();
  await page.waitForFunction(()=>!document.querySelector('#runError').hidden);
  assert.equal(await page.locator('#runError').isVisible(),true);
  assert.match(await page.locator('#runErrorMessage').textContent(),/测试引擎暂时不可用/);
  assert.equal(await page.locator('#runButton').isEnabled(),true);
  assert.equal(await page.locator('#heroRun').isEnabled(),true);
  await page.unroute('**/api/run');
  await page.locator('#retryRun').click();
  await page.waitForFunction(()=>document.querySelector('#runError').hidden&&document.querySelector('#playState').textContent==='运行中');
  record('failed requests display a visible error in detail views and recover on retry');
  await page.locator('[data-view="tasks"]').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#tasksExport').click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'teaflow-simulation.json');
  record('simulation results export as JSON');
  await page.locator('[data-view="overview"]').click();
  for(const width of [1920,1600,1432,1050,760,390]){
    await page.setViewportSize({width,height:1000});
    await page.waitForTimeout(120);
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
    assert.ok(overflow<=1,`horizontal overflow at ${width}: ${overflow}`);
  }
  record('no horizontal page overflow at 1920, 1600, 1432, 1050, 760 and 390 px');
  const motion=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN',reducedMotion:'no-preference'});
  motion.on('pageerror',error=>errors.push(error.message));
  await motion.goto(base);
  await motion.waitForFunction(()=>document.querySelector('#playState').textContent==='等待开始');
  await motion.locator('#footerWordmark').scrollIntoViewIfNeeded();
  await motion.waitForFunction(()=>document.querySelector('#footerWordmark').classList.contains('is-ready'));
  await motion.waitForTimeout(150);
  const footerRest=await motion.locator('#footerDistortion').evaluate(c=>c.toDataURL());
  const rect=await motion.locator('#footerWordmark').boundingBox();
  await motion.mouse.move(rect.x+rect.width*.25,rect.y+rect.height*.5);
  await motion.mouse.move(rect.x+rect.width*.65,rect.y+rect.height*.5,{steps:10});
  const footerMoved=await motion.locator('#footerDistortion').evaluate(c=>c.toDataURL());
  assert.notEqual(footerRest,footerMoved);
  await motion.mouse.move(1,1);
  await motion.waitForTimeout(1800);
  assert.equal(await motion.locator('#footerDistortion').evaluate(c=>c.toDataURL()),footerRest);
  record('footer distortion responds to pointer movement and settles back');
  await motion.locator('#sessionTitle').scrollIntoViewIfNeeded();
  await motion.waitForTimeout(500);
  const heading=await motion.locator('#sessionTitle').boundingBox();
  await motion.mouse.move(heading.x+heading.width*.2,heading.y+heading.height*.5);
  await motion.mouse.move(heading.x+heading.width*.65,heading.y+heading.height*.5,{steps:10});
  await motion.waitForFunction(()=>document.querySelectorAll('.signal-overlay').length>0);
  assert.equal(await motion.locator('.signal-overlay').first().evaluate(c=>getComputedStyle(c).pointerEvents),'none');
  await motion.mouse.move(1,1);
  await motion.waitForFunction(()=>document.querySelectorAll('.signal-overlay').length===0);
  record('functional hover creates a nonblocking overlay and releases it after decay');
  await motion.locator('#openSettings').click();
  await motion.locator('#signalMotionEnabled').uncheck();
  await motion.locator('#footerMotionEnabled').uncheck();
  await motion.locator('#customFooterText').fill('茶歇 OS');
  await motion.locator('#saveConfig').click();
  await motion.reload();
  await motion.waitForFunction(()=>!document.querySelector('#heroRun').disabled);
  assert.equal(await motion.locator('#footerWordmarkText').textContent(),'茶歇 OS');
  await motion.locator('#openSettings').click();
  assert.equal(await motion.locator('#signalMotionEnabled').isChecked(),false);
  assert.equal(await motion.locator('#footerMotionEnabled').isChecked(),false);
  await motion.locator('#closeSettings').click();
  await motion.locator('#footerWordmark').scrollIntoViewIfNeeded();
  const staticFooter=await motion.locator('#footerDistortion').evaluate(c=>c.toDataURL());
  const staticRect=await motion.locator('#footerWordmark').boundingBox();
  await motion.mouse.move(staticRect.x+staticRect.width*.2,staticRect.y+staticRect.height*.5);
  await motion.mouse.move(staticRect.x+staticRect.width*.7,staticRect.y+staticRect.height*.5,{steps:10});
  assert.equal(await motion.locator('#footerDistortion').evaluate(c=>c.toDataURL()),staticFooter);
  record('footer text and independent motion preferences persist and disable the effect');
  await motion.close();
  assert.deepEqual(errors,[]);
  record('no uncaught browser errors');
  fs.writeFileSync('results/browser/dashboard-regression.json',JSON.stringify({base,checks,pageErrors:errors},null,2));
} finally {await browser.close()}
